#!/bin/bash

# Initialize Machine-Specific Git Configuration - macOS and Linux
# Creates ~/.gitconfig.local with machine-specific paths, SSH commit signing,
# the HTTPS credential helper, and safe directories. The per-OS detection
# (credential helper, op-ssh-sign paths) lives in scripts/shared/platform.sh.
# The per-OS scripts in scripts/mac version/ and scripts/linux version/ are
# wrappers around this one.

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../shared/functions.sh
source "$SCRIPT_DIR/../shared/functions.sh"
# shellcheck source=../shared/platform.sh
source "$SCRIPT_DIR/../shared/platform.sh"

FORCE=false
HELP=false

while [[ $# -gt 0 ]]; do
    case $1 in
        -f|--force) FORCE=true; shift ;;
        -h|--help)  HELP=true;  shift ;;
        *) echo "Unknown option: $1"; exit 1 ;;
    esac
done

if [ "$HELP" = true ]; then
    cat << 'HELP'
Initialize Machine-Specific Git Configuration - macOS and Linux

USAGE:
    scripts/unix/initialize-local-config.sh [OPTIONS]

OPTIONS:
    -f, --force     Regenerate an existing .gitconfig.local without prompting
                    (the old file is kept as .gitconfig.local.bak.<timestamp>)
    -h, --help      Display this help message

DESCRIPTION:
    Creates ~/.gitconfig.local with machine-specific settings. This file is
    included by the main .gitconfig and should NOT be version controlled.
    - Global gitignore path
    - SSH commit signing: prefers an on-disk key file (~/.ssh/claude_desktop or
      ~/.ssh/id_ed25519_signing, with its .pub, and the optional
      ~/.ssh/git-sign-no-agent wrapper); falls back to 1Password's
      op-ssh-sign if installed (with the configured user.signingkey);
      otherwise, if git already has a user.signingkey, keeps it and writes
      allowedSignersFile so signatures verify. commit.gpgsign is only
      switched on when a key is configured and, for a configured key without
      a key file or op-ssh-sign, only when the file exists or the SSH agent
      lists it
    - core.editor: code --wait when VS Code is on PATH in a desktop session
      (not over SSH or headless); otherwise left unset
    - HTTPS credential helper: the macOS login keychain (osxkeychain) on
      macOS; the GitHub CLI (gh auth git-credential), else libsecret, on Linux
    - Safe directory entries (plus Homebrew's repo on a shared Mac where
      another account owns it)
    Regenerating keeps every setting you added to the file (aliases, includes,
    extra safe directories, ...). Only the settings listed above are rebuilt.
    A ~/.gitconfig.local symlink is replaced by a regular file; the file it
    points to is not changed.

EXIT STATUS:
    0 written (or already up to date), 1 error, 2 not regenerated because
    the prompt was declined or had no input (use --force when unattended)
HELP
    exit 0
fi

# Guard: the credential helper differs per OS, and the wrong platform's config
# breaks HTTPS auth: the macOS script once wrote credential.helper =
# osxkeychain on the Ubuntu server (issue #179). Run directly, this script
# targets the host; through a per-OS wrapper it refuses a host of the other
# kind. Tests set GITCONFIG_ALLOW_CROSS_OS=1 to run either platform's
# behaviour in a sandbox anywhere.
TARGET_OS="$(resolve_target_os script initialize-local-config.sh)" || exit 1
OS_NAME="$(os_display_name "$TARGET_OS")"

HOME_DIR="$HOME"
LOCAL_CONFIG_PATH="$HOME_DIR/.gitconfig.local"

echo "Git Local Configuration Setup ($OS_NAME)"
echo "======================================="
echo "Home Directory: $HOME_DIR"
echo "Local Config Path: $LOCAL_CONFIG_PATH"
echo ""

if { [ -f "$LOCAL_CONFIG_PATH" ] || [ -L "$LOCAL_CONFIG_PATH" ]; } && [ "$FORCE" = false ]; then
    echo ".gitconfig.local already exists (settings you added to it are kept)."
    # Declining (or no input to answer with) exits 2, so install.sh can tell
    # "kept the existing file" from success and from failure (#258).
    if ! ask_yes_no "Regenerate it?"; then
        echo "Cancelled."
        exit 2
    fi
fi

CONFIG_CONTENT="# Machine-Specific Git Configuration ($OS_NAME)
# Auto-generated by initialize-local-config.sh — do NOT commit this file

[core]
	excludesfile = $HOME_DIR/.gitignore_global
"

# --- Editor ------------------------------------------------------------------
# core.editor moved here from the template (#231): `code --wait` fails over
# SSH and on a headless machine. An editor already in the file is the user's
# choice and is kept as it is (with the other settings the user added, below).
if [ -f "$LOCAL_CONFIG_PATH" ] && git config --file "$LOCAL_CONFIG_PATH" --get core.editor >/dev/null 2>&1; then
    :
else
    detect_default_editor "$TARGET_OS"
    if [ -n "$DEFAULT_EDITOR" ]; then
        echo "[INFO] Using VS Code as the commit message editor: $DEFAULT_EDITOR"
        CONFIG_CONTENT+="	editor = $DEFAULT_EDITOR
"
    else
        echo "[INFO] Not setting core.editor: $DEFAULT_EDITOR_WHY."
        echo "       git uses \$GIT_EDITOR, \$VISUAL or \$EDITOR, else vi."
        CONFIG_CONTENT+="	# Not set: $DEFAULT_EDITOR_WHY, so git uses
	# \$GIT_EDITOR, \$VISUAL or \$EDITOR, else vi. To use VS Code:
	# editor = code --wait
"
    fi
fi

# --- SSH commit signing ------------------------------------------------------
detect_signing_key "$TARGET_OS" "$HOME_DIR"

SIGNING_ENABLED=false
case "$SIGNING_MODE" in
    file)
        # File-based key wins over op-ssh-sign: agent-based signing prompts for
        # Touch ID on every commit and hangs unattended runs (issue #171).
        echo "[INFO] Detected on-disk SSH signing key: $SIGNING_KEY_FILE"
        SIGNING_ENABLED=true
        CONFIG_CONTENT+="
[user]
	# Sign with the on-disk private key file — no SSH agent, no Touch ID
	# prompt. Must be the private key PATH (not the .pub): if the same key is
	# also loaded in an agent, ssh-keygen would route a .pub through it.
	signingkey = $SIGNING_KEY_FILE

[gpg]
	format = ssh

[gpg \"ssh\"]
	# Lets git verify SSH commit signatures locally (git log --show-signature)
	allowedSignersFile = $HOME_DIR/.ssh/allowed_signers
"
        if [ -n "$SIGNING_PROGRAM" ]; then
            echo "[INFO] Using no-agent signing wrapper: $SIGNING_PROGRAM"
            CONFIG_CONTENT+="	# Sign via a wrapper that unsets SSH_AUTH_SOCK so ssh-keygen reads the
	# private key from disk instead of the 1Password agent (Touch ID prompt).
	program = $SIGNING_PROGRAM
"
        fi
        CONFIG_CONTENT+="
[commit]
	gpgsign = true
"
        ;;
    op)
        # op-ssh-sign signs with a key held in 1Password; git still needs to be
        # told which one (user.signingkey, the public key). The template used to
        # supply one for every machine; now it must be configured here (#231),
        # so signing is only switched on when one is.
        echo "[INFO] Detected 1Password SSH signing helper: $SIGNING_PROGRAM"
        if [ -n "$EXISTING_SIGNING_KEY" ]; then
            echo "       Signing with the configured key: $EXISTING_SIGNING_KEY"
            SIGNING_ENABLED=true
            CONFIG_CONTENT+="
[user]
	signingkey = $EXISTING_SIGNING_KEY
"
        else
            echo "[WARN] No user.signingkey is configured, so commit signing is left off."
            echo "       Copy the key's public key from 1Password, then run:"
            echo "         git config --file ~/.gitconfig.local user.signingkey 'ssh-ed25519 AAAA...'"
            echo "         git config --file ~/.gitconfig.local commit.gpgsign true"
        fi
        CONFIG_CONTENT+="
[gpg]
	format = ssh

[gpg \"ssh\"]
	program = $SIGNING_PROGRAM
	# Lets git verify SSH commit signatures locally (git log --show-signature)
	allowedSignersFile = $HOME_DIR/.ssh/allowed_signers
"
        if [ "$SIGNING_ENABLED" = true ]; then
            CONFIG_CONTENT+="
[commit]
	gpgsign = true
"
        else
            CONFIG_CONTENT+="
# Set the signing key (the public key from 1Password), then uncomment:
# [user]
# 	signingkey = ssh-ed25519 AAAA...
# [commit]
# 	gpgsign = true
"
        fi
        ;;
    existing)
        # No key file and no op-ssh-sign, but git already has a signing key (set
        # by hand, or moved here from an older template, #231). Keep it, and
        # write allowedSignersFile or verification reports "No signature"
        # (issue #116). Omit the program. Signing is only switched on when the
        # machine holds the key: the file exists, or the SSH agent lists it.
        echo "[INFO] op-ssh-sign not found, but a signing key is configured:"
        echo "       $EXISTING_SIGNING_KEY"
        echo "       Writing allowedSignersFile so signatures verify locally."
        SIGNING_ENABLED=true
        CONFIG_CONTENT+="
[user]
	signingkey = $EXISTING_SIGNING_KEY

[gpg]
	format = ssh

[gpg \"ssh\"]
	# Lets git verify SSH commit signatures locally (git log --show-signature)
	allowedSignersFile = $HOME_DIR/.ssh/allowed_signers
"
        if signing_key_available "$EXISTING_SIGNING_KEY" "$HOME_DIR"; then
            CONFIG_CONTENT+="
[commit]
	gpgsign = true
"
        else
            echo "[WARN] This machine doesn't hold that key (no such key file, and the SSH"
            echo "       agent doesn't list it), so commit signing is left off. Once the key"
            echo "       is available, run: git config --file ~/.gitconfig.local commit.gpgsign true"
            CONFIG_CONTENT+="
# Signing is off: this machine didn't hold the key above when this file was
# generated. Once it does, uncomment:
# [commit]
# 	gpgsign = true
"
        fi
        ;;
    *)
        echo "[INFO] No signing key found and op-ssh-sign not installed — skipping signing config."
        echo "       Preferred: create an on-disk key (~/.ssh/id_ed25519_signing), register it"
        echo "       on GitHub as a signing key, then re-run this script."
        if [ "$TARGET_OS" = macos ]; then
            echo "       Or install 1Password: brew install 1password-cli"
            CONFIG_CONTENT+="
# Uncomment and set program path to enable SSH commit signing:
# [gpg]
# 	format = ssh
# [gpg \"ssh\"]
# 	program = /opt/homebrew/bin/op-ssh-sign
# [commit]
# 	gpgsign = true
"
        else
            CONFIG_CONTENT+="
# Uncomment to enable file-based SSH commit signing:
# [user]
# 	signingkey = $HOME_DIR/.ssh/id_ed25519_signing
# [gpg]
# 	format = ssh
# [commit]
# 	gpgsign = true
"
        fi
        ;;
esac

# --- HTTPS credential helper -------------------------------------------------
# Without one, unattended git over HTTPS fails ("could not read Username for
# 'https://github.com'"), e.g. `bd dolt push` or scheduled pulls of private
# repos (issue #179). Every block starts with an empty `helper =` line:
# credential.helper is multi-valued and accumulates, so a stale helper from
# another config level would otherwise answer first (issues #180, #183).
detect_credential_helper "$TARGET_OS"
case "$CREDENTIAL_HELPER_KIND" in
    osxkeychain)
        CONFIG_CONTENT+="
[credential]
	# Lets unattended HTTPS pulls of private repos (e.g. the claude-skills
	# launchd sync) authenticate from the macOS login keychain — no prompt and
	# no 1Password dependency. Store a token once with:
	#   git credential-osxkeychain store
	# The empty helper line resets helpers inherited from other config levels:
	# credential.helper is multi-valued and accumulates, so a stale helper from
	# a migrated other-platform config would otherwise answer first (issue #183,
	# mirroring the Linux blocks from #180).
	helper =
	helper = osxkeychain
"
        ;;
    gh)
        echo "[INFO] Using GitHub CLI credential helper: $CREDENTIAL_HELPER_PATH"
        echo "       Run 'gh auth login' once if you haven't — the helper reads gh's token."
        CONFIG_CONTENT+="
[credential \"https://github.com\"]
	# HTTPS auth from the gh CLI token, so unattended git over HTTPS (e.g.
	# \`bd dolt push\`, cron pulls of private repos) never prompts. The empty
	# helper line resets any helpers inherited from other config levels.
	helper =
	helper = !$CREDENTIAL_HELPER_PATH auth git-credential

[credential \"https://gist.github.com\"]
	helper =
	helper = !$CREDENTIAL_HELPER_PATH auth git-credential
"
        ;;
    libsecret)
        echo "[INFO] Using libsecret credential helper: $CREDENTIAL_HELPER_PATH"
        CONFIG_CONTENT+="
[credential]
	# HTTPS auth from the desktop keyring via libsecret — no prompt once a
	# token has been stored (first interactive push/pull saves it). The empty
	# helper line resets any helpers inherited from other config levels, so a
	# stale one can't answer first with an expired credential (issue #179).
	helper =
	helper = $CREDENTIAL_HELPER_PATH
"
        ;;
    *)
        echo "[INFO] No credential helper found (gh CLI or libsecret) — skipping."
        echo "       Install the GitHub CLI (https://cli.github.com) and run 'gh auth login',"
        echo "       then re-run this script to enable unattended HTTPS auth."
        CONFIG_CONTENT+="
# Uncomment to enable HTTPS auth via the GitHub CLI (after 'gh auth login'):
# [credential \"https://github.com\"]
# 	helper =
# 	helper = !gh auth git-credential
"
        ;;
esac

# --- Safe directories --------------------------------------------------------
CONFIG_CONTENT+="
[safe]
	# Add trusted local or network directories here:
	# directory = /path/to/trusted/repo
	directory = $HOME_DIR/Documents/Scripts/gitconfig
"

# On a shared Mac, /opt/homebrew can be owned by a different account. git then
# refuses to read Homebrew's repo ("detected dubious ownership"), which breaks
# `brew update` with "fatal: not in a git directory". Trust the repo whenever
# it exists and belongs to someone else. HOMEBREW_REPO is overridable so tests
# can point it at a sandbox path.
if [ "$TARGET_OS" = macos ]; then
    HOMEBREW_REPO="${HOMEBREW_REPO:-/opt/homebrew}"
    if [ -d "$HOMEBREW_REPO/.git" ] && [ "$(file_owner_uid "$HOMEBREW_REPO")" != "$(id -u)" ]; then
        echo "[INFO] $HOMEBREW_REPO is owned by another user — adding it as a safe directory so brew update works."
        CONFIG_CONTENT+="	# Homebrew's repo is owned by another account on this shared machine;
	# without this entry git's dubious-ownership check breaks \`brew update\`.
	directory = $HOMEBREW_REPO
"
    fi
fi

# --- Settings the user added -------------------------------------------------
# install.sh and the ~/.gitconfig regeneration tell users to put their own git
# settings here, so regenerating (--force, or "y" at the prompt) must keep
# them (#257). Everything this script doesn't generate is carried over below
# its own header; the generated settings are rebuilt from what was detected.
if [ -f "$LOCAL_CONFIG_PATH" ]; then
    KEPT_FILE="$(mktemp "${TMPDIR:-/tmp}/gitconfig-local-kept.XXXXXX")"
    if keep_local_settings "$LOCAL_CONFIG_PATH" "$CONFIG_CONTENT" "$KEPT_FILE"; then
        if [ -s "$KEPT_FILE" ]; then
            CONFIG_CONTENT+="
$LOCAL_CONFIG_KEPT_HEADER
$(cat "$KEPT_FILE")"
        fi
    else
        echo "[WARN] Could not read the existing .gitconfig.local (is it valid git config?),"
        echo "       so none of its settings are carried over. The backup below keeps them."
    fi
    rm -f "$KEPT_FILE"
fi

# A symlink (into a dotfiles repo, say) is backed up and replaced, never
# written through (#257). Otherwise keep a timestamped copy of the file we are
# about to replace, unless it already holds exactly what we would write.
if [ -L "$LOCAL_CONFIG_PATH" ]; then
    detach_symlink "$LOCAL_CONFIG_PATH"
elif [ -f "$LOCAL_CONFIG_PATH" ] && [ "$(cat "$LOCAL_CONFIG_PATH")" != "$(printf '%s\n' "$CONFIG_CONTENT")" ]; then
    backup_copy "$LOCAL_CONFIG_PATH"
fi

printf '%s\n' "$CONFIG_CONTENT" > "$LOCAL_CONFIG_PATH"
echo "[OK] Created .gitconfig.local"
echo ""

# When signing is enabled, register the signing identity so git can verify
# SSH commit signatures locally.
if [ "$SIGNING_ENABLED" = true ]; then
    update_allowed_signers "$HOME_DIR/.ssh/allowed_signers"
    echo ""
fi

echo "To add safe directories, edit: $LOCAL_CONFIG_PATH"
echo ""
